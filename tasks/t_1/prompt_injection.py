def main():
    # TODO 1: Implementation
    # 1. Create AzureChatOpenAI client with mini/nano model
    # 2. Create messages array with system prompt and PROFILE data as HumanMessage
    # 3. Create console chat with message history preservation for multi-step prompt injection testing
    client = AzureChatOpenAI(
        api_key=SecretStr(API_KEY),
        api_version="2024-08-01-preview",
        azure_endpoint=DIAL_URL,
        model="gpt-4.1-nano-2025-04-14"  # Using nano model for cost efficiency
    )

    messages: list[BaseMessage] = [
        SystemMessage(content=SYSTEM_PROMPT),
        HumanMessage(content=PROFILE)
    ]

    print("Starting secure directory assistant...")
    print("(Type 'exit' to quit)\n")

    while True:
        user_input = input("You: ").strip()

        if user_input.lower() == "exit":
            break

        if not user_input:
            continue

        messages.append(HumanMessage(content=user_input))

        response = client.invoke(messages)
        assistant_message = response.content

        messages.append(response)

        print(f"Assistant: {assistant_message}\n")


if __name__ == "__main__":
    main()

